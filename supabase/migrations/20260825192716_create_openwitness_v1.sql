-- 38. PUBLIC INCIDENT VIEW
-- ============================================================
--
-- security_invoker ensures underlying RLS remains effective.
--
-- ============================================================

create or replace view public.public_incidents
with (
  security_invoker = true
)
as

select

  i.id,

  i.public_id,

  i.title,

  i.description,

  i.incident_date,

  i.verification_status,

  i.published_at,

  c.name as category,

  c.slug as category_slug,

  d.name as division,

  d.slug as division_slug,

  ds.name as district,

  ds.slug as district_slug

from public.incidents i

join public.categories c
  on c.id = i.category_id

join public.divisions d
  on d.id = i.division_id

join public.districts ds
  on ds.id = i.district_id

where i.status = 'approved';


revoke all
on public.public_incidents
from anon, authenticated;


grant select
on public.public_incidents
to anon, authenticated;


