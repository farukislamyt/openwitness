-- ============================================================
-- 21. AUTOMATIC MODERATION AUDIT
-- ============================================================
--
-- Status changes are automatically recorded.
--
-- Content changes are automatically recorded as "edited".
--
-- This prevents a moderator from changing an incident status
-- without creating an audit trail.
--
-- ============================================================

create or replace function private.audit_incident_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare

  staff_id uuid;

  audit_action public.moderation_action_type;

begin

  staff_id := private.current_staff_id();

  -- No authenticated staff identity:
  -- do not create an application-level audit record.
  --
  -- This can occur during migrations or trusted database
  -- administration.

  if staff_id is null then
    return new;
  end if;


  -- Status transition audit.

  if new.status is distinct from old.status then

    audit_action :=
      case new.status
        when 'under_review'
          then 'started_review'::public.moderation_action_type

        when 'approved'
          then 'approved'::public.moderation_action_type

        when 'rejected'
          then 'rejected'::public.moderation_action_type

        when 'needs_revision'
          then 'needs_revision'::public.moderation_action_type

        when 'archived'
          then 'archived'::public.moderation_action_type

        else
          null
      end;


    if audit_action is not null then

      insert into public.moderation_actions (
        incident_id,
        admin_user_id,
        action,
        notes
      )
      values (
        new.id,
        staff_id,
        audit_action,
        null
      );

    end if;

  end if;


  -- Content/location/category/date modification audit.

  if
    new.title is distinct from old.title
    or new.description is distinct from old.description
    or new.category_id is distinct from old.category_id
    or new.division_id is distinct from old.division_id
    or new.district_id is distinct from old.district_id
    or new.incident_date is distinct from old.incident_date
    or new.verification_status is distinct from old.verification_status
  then

    insert into public.moderation_actions (
      incident_id,
      admin_user_id,
      action,
      notes
    )
    values (
      new.id,
      staff_id,
      'edited'::public.moderation_action_type,
      null
    );

  end if;


  return new;

end;
$$;


revoke all
on function private.audit_incident_change()
from public;

revoke all
on function private.audit_incident_change()
from anon;

revoke all
on function private.audit_incident_change()
from authenticated;


create trigger incidents_audit_changes
